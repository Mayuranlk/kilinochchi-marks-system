const fs = require("node:fs");
const { test, expect } = require("@playwright/test");
const { initializeApp } = require("firebase-admin/app");
const { getFirestore, FieldValue } = require("firebase-admin/firestore");

let db;
test.beforeAll(async () => {
  if (process.env.FIRESTORE_EMULATOR_HOST !== "127.0.0.1:8085" || process.env.GCLOUD_PROJECT !== "demo-kilinochchi-rules") throw new Error("SBA tests require the isolated demo emulator.");
  db = getFirestore(initializeApp({ projectId: "demo-kilinochchi-rules" }, "sba-tests"));
  fs.mkdirSync("audit-output/sba", { recursive: true });
});
async function login(page, role) {
  await page.goto("/login");
  await page.locator('input[type="email"]').fill(`${role}@app-emulator.test`);
  await page.locator('input[type="password"]').fill("EmulatorOnly!123");
  await page.getByRole("button", { name: /sign in/i }).click();
  await expect(page).toHaveURL(role === "admin" ? /\/$/ : /\/teacher$/);
}

test("SBA teacher entry, conflict protection, A3 print and admin deletion remain isolated from term marks", async ({ page, browser }) => {
  const browserErrors = [];
  page.on("pageerror", (error) => browserErrors.push(error.message));
  const termBefore = (await db.collection("marks").get()).docs.map((item) => ({ id: item.id, ...item.data() }));
  await login(page, "teacher");
  await page.goto("/teacher/sba-marks");
  const first = page.getByRole("textbox", { name: "SBA mark for Synthetic Student One", exact: true });
  const second = page.getByRole("textbox", { name: "SBA mark for Synthetic Student Two", exact: true });
  await expect(first).toBeEnabled();
  await first.fill("21");
  await page.getByRole("button", { name: "Save SBA marks", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "between 0 and 20" })).toBeVisible();
  expect((await db.collection("sbaMarks").get()).size).toBe(0);
  await first.fill("17.5");
  await second.fill("0");
  await expect(page.getByRole("combobox").first()).toHaveAttribute("aria-disabled", "true");
  await page.getByRole("button", { name: "Save SBA marks", exact: true }).click();
  await expect(page.getByText("2 SBA record(s) saved.", { exact: true })).toBeVisible();
  const firstRef = db.collection("sbaMarks").doc("term-2026-1~student-001~subject-mathematics");
  expect((await firstRef.get()).data().mark).toBe(17.5);
  await page.reload();
  await expect(first).toHaveValue("17.5");
  await expect(second).toHaveValue("0");
  await firstRef.update({ mark: 19, revision: 2, updatedAt: FieldValue.serverTimestamp() });
  await first.fill("18");
  await page.getByRole("button", { name: "Save SBA marks", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "another session" })).toBeVisible();
  expect((await firstRef.get()).data().mark).toBe(19);
  await page.getByRole("button", { name: "Discard changes" }).click();
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await expect(first).toHaveValue("19");
  await page.getByRole("checkbox", { name: "Absent: Synthetic Student Two", exact: true }).check();
  await page.getByRole("button", { name: "Save SBA marks", exact: true }).click();
  await expect(page.getByText("1 SBA record(s) saved.", { exact: true })).toBeVisible();
  await page.screenshot({ path: "audit-output/sba/entry-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect.poll(() => page.getByRole("table", { name: "SBA marks entry" }).evaluate((table) => table.parentElement.scrollWidth <= table.parentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: "audit-output/sba/entry-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "A3 class register" }).click();
  const preview = page.frameLocator('iframe[title="SBA A3 register preview"]');
  await expect(preview.locator(".sheet")).toHaveCount(2);
  await expect(preview.locator("tbody").last()).toContainText("AB");
  await expect(preview.locator("tbody").first()).toContainText("19");
  const [popup] = await Promise.all([page.waitForEvent("popup"), page.getByRole("button", { name: "Print / Save A3 PDF" }).click()]);
  await popup.waitForLoadState();
  await popup.evaluate(() => document.fonts.ready);
  await popup.pdf({ path: "audit-output/sba/register.pdf", preferCSSPageSize: true, printBackground: true });
  await popup.close();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "audit-output/sba/register-mobile.png", fullPage: true });
  await db.collection("systemSettings").doc("sbaEntry").set({ teacherEntryEnabled: false });
  await page.goto("/teacher/sba-marks");
  await expect(page.getByText("SBA entry is closed.", { exact: false })).toBeVisible();
  await expect(first).toBeDisabled();
  const adminContext = await browser.newContext();
  const adminPage = await adminContext.newPage();
  await login(adminPage, "admin");
  await adminPage.goto("/sba-marks");
  await expect(adminPage.getByRole("textbox", { name: "SBA mark for Synthetic Student One", exact: true })).toBeEnabled();
  await adminPage.getByRole("row").filter({ hasText: "Synthetic Student One" }).getByRole("button", { name: "Delete SBA", exact: true }).click();
  await adminPage.getByRole("button", { name: "Delete SBA record", exact: true }).click();
  await expect(adminPage.getByText("1 SBA record(s) deleted.", { exact: true })).toBeVisible();
  expect((await firstRef.get()).exists).toBe(false);
  expect((await db.collection("marks").get()).docs.map((item) => ({ id: item.id, ...item.data() }))).toEqual(termBefore);
  expect(browserErrors).toEqual([]);
  await adminContext.close();
});

test("SBA register matches the 22-column English A3 layout", async ({ page }) => {
  const names = ["Tamil", "English", "Science", "History", "Hinduism", "Catholicism", "Christianity", "Art", "Music", "Dance", "Drama and Theatre (Tamil)", "Appreciation of Tamil Literary Texts", "Appreciation of English Literary Texts", "Civics", "Geography", "Entrepreneurship Studies", "Business & Accounting Studies", "Health & Physical Education", "ICT", "Home Economics", "Agriculture & Food Technology"];
  const batch = db.batch();
  names.forEach((subjectName, index) => {
    const subjectId = `sba-layout-subject-${index}`;
    batch.set(db.collection("teacherAssignments").doc(`sba-layout-assignment-${index}`), { teacherId: "app-it-teacher", teacherName: "Synthetic Subject Teacher", subjectId, subjectName, grade: 10, section: "A", fullClassName: "10A", medium: "", status: "active" });
    batch.set(db.collection("studentSubjectEnrollments").doc(`sba-layout-enrollment-${index}`), { studentId: "student-001", subjectId, subjectName, academicYear: "2026", grade: 10, section: "A", fullClassName: "10A", status: "active" });
  });
  const longName = "Synthetic Student One With A Long Family Name And Additional Given Names Preserved In The Register";
  batch.update(db.collection("students").doc("student-001"), { name: longName, fullName: longName });
  await batch.commit();
  await login(page, "admin");
  await page.goto("/sba-register");
  const preview = page.frameLocator('iframe[title="SBA A3 register preview"]');
  await expect(preview.locator(".sheet")).toHaveCount(2);
  await expect(preview.locator("thead").first().locator("th")).toHaveCount(24);
  await expect(preview.locator("thead").first()).toContainText("Tamil Literature");
  const [popup] = await Promise.all([page.waitForEvent("popup"), page.getByRole("button", { name: "Print / Save A3 PDF" }).click()]);
  await popup.waitForLoadState();
  await popup.evaluate(() => document.fonts.ready);
  await popup.pdf({ path: "audit-output/sba/register-22-subjects.pdf", preferCSSPageSize: true, printBackground: true });
  await popup.screenshot({ path: "audit-output/sba/register-22-subjects.png", fullPage: true });
  await popup.close();
  await page.getByRole("button", { name: "WhatsApp", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("button", { name: "Download PDF", exact: true })).toBeEnabled({ timeout: 30000 });
  const [download] = await Promise.all([page.waitForEvent("download"), dialog.getByRole("button", { name: "Download PDF", exact: true }).click()]);
  await download.saveAs("audit-output/sba/english-share-register.pdf");
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
});


test("admin SBA prerequisite locks and unlocks teacher term entry without mixing marks", async ({ page, browser }) => {
  await db.collection("practiceExams").doc("practice-2026-1").update({ grade: 10 });
  const settings = db.collection("systemSettings").doc("marksEntry");
  await settings.set({ teacherEntryEnabled: true, teacherEntryDeadline: "", requireSbaCompletion: false });
  await login(page, "admin");
  const toggle = page.getByRole("switch", { name: "Require completed SBA before term marks" });
  await toggle.check();
  await page.getByRole("button", { name: "Save Access", exact: true }).click();
  await expect.poll(async () => (await settings.get()).data().requireSbaCompletion).toBe(true);
  const context = await browser.newContext();
  const teacherPage = await context.newPage();
  await login(teacherPage, "teacher");
  await teacherPage.goto("/teacher/marks");
  await expect(teacherPage.getByText(/Enter SBA Marks to Enable term marks entry/)).toBeVisible();
  await expect(teacherPage.locator('input[value="74"]').first()).toBeDisabled();
  const allStudents = (await db.collection("students").get()).docs;
  const batch = db.batch();
  for (const student of allStudents) {
    const termId = "term-2026-1", subjectId = "subject-mathematics";
    batch.set(db.collection("sbaMarks").doc(`${termId}~${student.id}~${subjectId}`), { schemaVersion: 1, assessmentType: "sba", maxMark: 20, termId, year: "2026", classKey: "10|A|", scopeKey: `${termId}|10|A|`, subjectId, studentId: student.id, assignmentId: "assignment-teacher-maths-10a", enrollmentId: "test", mark: student.id === "student-002" ? null : 0, absent: student.id === "student-002", revision: 1, updatedBy: "app-admin", updatedAt: FieldValue.serverTimestamp() });
  }
  await batch.commit();
  const input = teacherPage.locator('input[value="74"]').first();
  await expect(input).toBeEnabled();
  const remainingInputs = teacherPage.locator('input[inputmode="decimal"]:enabled');
  for (let index = 0; index < await remainingInputs.count(); index++) await remainingInputs.nth(index).fill("84");
  await teacherPage.getByRole("row").filter({ hasText: "SYN001" }).locator('input[inputmode="decimal"]').fill("83");
  await teacherPage.getByRole("button", { name: "Save Marks", exact: true }).click();
  await expect(teacherPage.getByText("0 unsaved", { exact: true }).last()).toBeVisible();
  await expect(teacherPage.locator('input[value="83"]').first()).toBeVisible();
  expect((await db.collection("marks").where("studentId", "==", "student-001").get()).docs.some((item) => item.data().mark === 83)).toBe(true);
  const firstSba = db.collection("sbaMarks").doc("term-2026-1~student-001~subject-mathematics");
  expect((await firstSba.get()).data().mark).toBe(0);
  await firstSba.delete();
  await expect(teacherPage.locator('input[value="83"]').first()).toBeDisabled();
  await teacherPage.getByRole("combobox", { name: "Exam", exact: true }).click();
  await teacherPage.getByRole("option", { name: "Synthetic Practice 1", exact: true }).click();
  await expect(teacherPage.getByText(/Enter SBA Marks to Enable term marks entry/)).toHaveCount(0);
  await toggle.uncheck();
  await page.getByRole("button", { name: "Save Access", exact: true }).click();
  await teacherPage.getByRole("combobox", { name: "Exam", exact: true }).click();
  await teacherPage.getByRole("option", { name: "Main Term Exam", exact: true }).click();
  await expect(teacherPage.locator('input[value="83"]').first()).toBeEnabled();
  await context.close();
});
